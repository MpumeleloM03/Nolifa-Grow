#!/usr/bin/env python3
"""Builds packages/ubuntu_core/lib/zulu_strings.dart from order.json (the English
templates, frozen) and zu/*.txt (index<TAB>Zulu). zu/fixes.txt is read last and wins."""
import glob, json, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
order = json.load(open(os.path.join(here, 'order.json')))
zu = {}
files = sorted(f for f in glob.glob(os.path.join(here, 'zu', '*.txt')) if not f.endswith('fixes.txt'))
files.append(os.path.join(here, 'zu', 'fixes.txt'))
for f in files:
    if not os.path.exists(f): continue
    for n, line in enumerate(open(f, encoding='utf-8').read().split('\n'), 1):
        if not line.strip(): continue
        i, _, v = line.partition('\t')
        if not i.isdigit() or not _: print('bad line', f, n, line[:60]); continue
        zu[int(i)] = v

def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"

exact, templ, warn = {}, {}, []
GLOSS = {'izinduna': 'amathikhi'}  # ticks: izinduna means chiefs
for i, v in sorted(zu.items()):
    if i >= len(order): warn.append(f'index {i} out of range'); continue
    k = order[i]
    for a, b in GLOSS.items(): v = v.replace(a, b)
    v = v.replace(' — ', ' - ').replace('—', '-')  # no em dashes in anything shown
    lead = k[:len(k) - len(k.lstrip())]; trail = k[len(k.rstrip()):]
    v = lead + v.strip() + trail
    if v == k: continue
    miss = set(re.findall(r'\{\d+\}', k)) - set(re.findall(r'\{\d+\}', v))
    extra = set(re.findall(r'\{\d+\}', v)) - set(re.findall(r'\{\d+\}', k))
    if extra: warn.append(f'{i}: Zulu has placeholders the English does not: {extra}')
    if re.search(r'\{\d+\}', k): templ[k] = v
    else: exact[k] = v
    if miss and not (i in (341, 694, 1796, 2292)): pass

# strings found after the order was frozen, keyed by their English text
for line in open(os.path.join(here, 'zu', 'extra.tsv'), encoding='utf-8').read().split('\n'):
    if not line.strip(): continue
    k, _, v = line.partition('\t')
    v = v.replace('—', '-')
    if re.search(r'\{\d+\}', k): templ[k] = v
    else: exact[k] = v

# adjacent string literals in the source are one sentence at run time: join them
def renumber(piece, start):
    n = start
    def r(m):
        nonlocal n
        s_ = '{%d}' % n; n += 1; return s_
    return re.sub(r'\{\d+\}', r, piece), n
groups = json.load(open(os.path.join(here, 'groups.json')))
composed = 0
for g in groups:
    en_parts, zu_parts, n = [], [], 0
    changed = False
    for piece in g:
        z = templ.get(piece) if re.search(r'\{\d+\}', piece) else exact.get(piece)
        # keep the piece's own spaces
        if z is None: z = piece
        else: changed = True
        e2, n2 = renumber(piece, n)
        z2, _ = renumber(z, n)
        en_parts.append(e2); zu_parts.append(z2); n = n2
    if not changed: continue
    ek, zv = ''.join(en_parts), ''.join(zu_parts)
    if ek == zv: continue
    (templ if re.search(r'\{\d+\}', ek) else exact)[ek] = zv; composed += 1
print('composed', composed)

out = ['// Generated by tools/translate/gen.py. Do not edit by hand.',
       '// Zulu text for the apps, keyed by the English sentence. A {0} is a gap for a number or name.',
       '// Needs review by a first-language isiZulu speaker before store release.',
       'const Map<String, String> zuExact = {']
for k in sorted(exact): out.append(f'  {q(k)}: {q(exact[k])},')
out.append('};')
out.append('')
out.append('const List<(String, String)> zuTemplates = [')
for k in sorted(templ): out.append(f'  ({q(k)}, {q(templ[k])}),')
out.append('];')
path = os.path.join(here, '..', '..', 'packages', 'ubuntu_core', 'lib', 'zulu_strings.dart')
open(path, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
covered = len(zu)
skipped = [i for i in range(len(order)) if i not in zu]
print('translated', covered, 'exact', len(exact), 'templates', len(templ), 'untranslated', len(skipped))
for w in warn[:20]: print('WARN', w)
json.dump([order[i] for i in skipped], open(os.path.join(here, 'untranslated.json'), 'w'), ensure_ascii=False, indent=0)
